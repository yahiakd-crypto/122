import { NextResponse } from "next/server";
import { getProduct } from "@/lib/db";
import { buildImagePrompt } from "@/lib/aiImages/provider";

export async function POST(req) {
  const body = await req.json().catch(() => ({}));
  const projectId = body.projectId || body.sourceId;
  if (!projectId) return NextResponse.json({ error: "Project id required.", code: "bad_request" }, { status: 400 });
  const product = getProduct(projectId);
  const { prompt, contextAutoGenerated } = buildImagePrompt({
    prompt: "",
    product,
    audience: product?.targetAudience,
    settings: { creative: body.creative || "" },
  });
  return NextResponse.json({ prompt, autoGenerated: contextAutoGenerated });
}
