import { NextResponse } from "next/server";
import { getJob, createJob, countActiveJobs, todayGenerationCount, toPublicJob } from "@/lib/aiImages/store";
import { getInternalImageConfig, IMAGE_PROVIDERS } from "@/lib/aiImages/config";
import { kick } from "@/lib/aiImages/engine";
import { buildImagePrompt } from "@/lib/aiImages/provider";
import { getProduct } from "@/lib/db";

export async function POST(req) {
  const cfg = getInternalImageConfig();
  if (!cfg.enabled) {
    return NextResponse.json({ error: "Google AI image generation is disabled. Enable it in AI Studio Settings.", code: "disabled" }, { status: 400 });
  }

  let body;
  try {
    body = await req.json();
  } catch {
    return NextResponse.json({ error: "Invalid request body.", code: "bad_request" }, { status: 400 });
  }

  const provider = body.provider || cfg.provider;
  const model = body.model || cfg.model;
  const name = IMAGE_PROVIDERS[provider] ? provider : cfg.provider;

  // Rate limits (configurable).
  if (countActiveJobs() >= cfg.maxConcurrentJobs) {
    return NextResponse.json({ error: `Maximum concurrent generations reached (${cfg.maxConcurrentJobs}). Please wait for one to finish.`, code: "concurrency_limit" }, { status: 429 });
  }
  if (todayGenerationCount() >= cfg.dailyGenerationLimit) {
    return NextResponse.json({ error: `Daily generation limit reached (${cfg.dailyGenerationLimit}). Try again tomorrow.`, code: "daily_limit" }, { status: 429 });
  }

  const prompt = String(body.prompt || "").trim();
  const sourceId = body.sourceId || null;
  const sourceLabel = body.sourceLabel || "";

  // Auto-build the prompt from product context when requested/empty.
  let finalPrompt = prompt;
  let autoGenerated = Boolean(body.autoPrompt);
  if (!finalPrompt && sourceId) {
    const product = getProduct(sourceId);
    const built = buildImagePrompt({ product, prompt: "", audience: product?.targetAudience, settings: {} });
    finalPrompt = built.prompt;
    autoGenerated = true;
  }
  if (!finalPrompt) {
    return NextResponse.json({ error: "A prompt is required.", code: "missing_prompt" }, { status: 400 });
  }

  // Validate reference images were pre-uploaded (tokens, not raw data).
  const referenceImages = (Array.isArray(body.referenceImages) ? body.referenceImages : [])
    .map((r) => (typeof r === "string" ? r : r?.url || r?.dataUrl || null))
    .filter(Boolean)
    .slice(0, 4)
    .map((r) => ({ dataUrl: r }));

  const aspectRatio = /^(\d+)\s*:\s*\d+$/.test(String(body.aspectRatio || "1:1")) ? String(body.aspectRatio) : "1:1";
  const numberOfImages = Math.min(Math.max(1, parseInt(body.numberOfImages, 10) || 1), 4);

  const job = createJob({
    provider: name,
    model,
    prompt: finalPrompt,
    negativePrompt: String(body.negativePrompt || ""),
    aspectRatio,
    numberOfImages,
    referenceImages,
    sourceType: sourceId ? "product" : "manual",
    sourceId,
    sourceLabel: String(sourceLabel || "").slice(0, 120),
    maxAttempts: cfg.retryAttempts,
  });

  // Kick off the background worker immediately; respond without waiting.
  kick();

  return NextResponse.json({ job_id: job.id, status: "queued", auto_generated_prompt: autoGenerated });
}
